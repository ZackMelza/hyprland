#!/usr/bin/env bash
# Opt-in, reversible Lua entrypoint switch for an existing managed JaKooLit profile.
set -euo pipefail
usage() {
  printf 'Usage: %s --check|--activate|--restore\n' "$0"
}
[[ $# -eq 1 ]] || { usage; exit 2; }
action="$1"
case "$action" in --check|--activate|--restore) ;; *) usage; exit 2;; esac

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
active_dir="$HOME/.config/hypr"
managed_conf="$active_dir/hyprland.conf"
entry="$active_dir/hyprland.lua"
modules="$active_dir/lua"
source_entry="$repo_root/common/hyprland.lua"
source_modules="$repo_root/common/lua"
state_dir="${XDG_STATE_HOME:-$HOME/.local/state}/jakoolit-lua-recovery"
marker="$state_dir/last-activation"
expected="source = \$RepoRoot/common/hyprland.conf"

[[ -f "$source_entry" && -d "$source_modules" ]] || {
  echo "Lua sources not found. Pull the recovery branch first: $source_entry" >&2
  exit 1
}
[[ -f "$managed_conf" ]] && grep -qxF "$expected" "$managed_conf" || {
  echo "Refusing: not the expected managed JaKooLit .conf entrypoint: $managed_conf" >&2
  exit 1
}
[[ -d "$active_dir" ]] || { echo "Missing $active_dir" >&2; exit 1; }

if [[ "$action" == --check ]]; then
  printf 'Config directory resolves to: %s\n' "$(readlink -f "$active_dir")"
  printf 'Old entrypoint: %s\n' "$managed_conf"
  printf 'Lua entrypoint: %s\n' "$entry"
  if [[ -L "$entry" ]]; then
    printf 'Lua target: %s\n' "$(readlink "$entry")"
  elif [[ -f "$entry" ]]; then
    if grep -q 'AUTOGENERATED HYPRLAND CONFIG' "$entry"; then
      echo 'Lua is currently the autogenerated default example.'
    else
      echo 'Lua entrypoint is an existing custom regular file (will NOT overwrite).'
    fi
  else
    echo 'Lua entrypoint absent.'
  fi
  if [[ -L "$modules" ]]; then
    printf 'Lua modules target: %s\n' "$(readlink "$modules")"
  elif [[ -e "$modules" ]]; then
    echo 'Lua modules path exists (will NOT overwrite).'
  else
    echo 'Lua modules path absent.'
  fi
  exit 0
fi

if [[ "$action" == --activate ]]; then
  if [[ -e "$marker" ]]; then
    echo "An activation is already recorded at $marker; restore it first." >&2
    exit 1
  fi
  if [[ -e "$modules" || -L "$modules" ]]; then
    echo "Refusing: $modules already exists. Inspect it manually." >&2
    exit 1
  fi
  if [[ -L "$entry" ]]; then
    echo "Refusing: $entry is already a symlink. Inspect it manually." >&2
    exit 1
  fi
  if [[ -f "$entry" ]] && ! grep -q 'AUTOGENERATED HYPRLAND CONFIG' "$entry"; then
    echo "Refusing: $entry is not the known autogenerated example." >&2
    exit 1
  fi
  backup="$state_dir/backup-$(date +%Y%m%d-%H%M%S)"
  mkdir -p "$backup"
  cp -a "$managed_conf" "$backup/hyprland.conf"
  if [[ -f "$entry" ]]; then
    cp -a "$entry" "$backup/hyprland.lua"
    printf 'present\n' > "$backup/entry-status"
  else
    printf 'absent\n' > "$backup/entry-status"
  fi
  ln -s "$source_modules" "$modules"
  rm -f -- "$entry"
  ln -s "$source_entry" "$entry"
  printf '%s\n' "$backup" > "$marker"
  echo "Activated Lua entrypoint with backup at $backup"
  echo "IMPORTANT: No Hyprland reload was performed."
  echo "Inspect modules, then run 'hyprctl reload' when ready."
  echo "Rollback: $repo_root/stage-lua-recovery.sh --restore"
  exit 0
fi

[[ -f "$marker" ]] || { echo "No managed activation marker; nothing to restore." >&2; exit 1; }
backup="$(cat "$marker")"
[[ -f "$backup/entry-status" ]] || { echo "Missing rollback metadata: $backup" >&2; exit 1; }
[[ -L "$entry" && "$(readlink "$entry")" == "$source_entry" ]] || {
  echo "Refusing: Lua entrypoint has changed since activation." >&2; exit 1;
}
[[ -L "$modules" && "$(readlink "$modules")" == "$source_modules" ]] || {
  echo "Refusing: Lua modules link has changed since activation." >&2; exit 1;
}
rm -- "$entry" "$modules"
if [[ "$(cat "$backup/entry-status")" == present ]]; then
  cp -a "$backup/hyprland.lua" "$entry"
fi
rm -- "$marker"
echo "Restored original Lua entrypoint state; backup retained: $backup"
echo "No Hyprland reload was performed."
