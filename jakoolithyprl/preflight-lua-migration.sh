#!/usr/bin/env bash
# Read-only audit of a managed JaKooLit installation before Lua migration.
# Never writes to the active config, never launches an installer or reloads Hyprland.
set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$script_dir"
configured_dir="${XDG_CONFIG_HOME:-$HOME/.config}/hypr"
active_dir="$(readlink -f -- "$configured_dir" 2>/dev/null || true)"

report_path() {
  local path="$1"
  local label="$2"
  if [[ -L "$path" ]]; then
    printf '%-33s symlink -> %s\n' "$label" "$(readlink -- "$path")"
  elif [[ -f "$path" ]]; then
    printf '%-33s regular file (%s bytes)\n' "$label" "$(wc -c <"$path")"
  elif [[ -d "$path" ]]; then
    printf '%-33s directory\n' "$label"
  elif [[ -e "$path" ]]; then
    printf '%-33s exists (other)\n' "$label"
  else
    printf '%-33s MISSING\n' "$label"
  fi
}

printf '%s\n' '== JaKooLit Lua migration preflight (read-only) =='
printf 'Checkout: %s\n' "$repo_root"
printf 'Active config path: %s\n' "$configured_dir"
printf 'Resolved config path: %s\n' "$active_dir"
if [[ -L "$configured_dir" ]]; then
  printf 'Config link target: %s\n' "$(readlink -- "$configured_dir")"
fi

printf '\n%s\n' '== Git =='
if git -C "$repo_root" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  printf 'Branch: %s\n' "$(git -C "$repo_root" branch --show-current)"
  printf 'Tracked working tree changes:\n'
  git -C "$repo_root" status --short --untracked-files=no
else
  echo 'Could not locate repo Git metadata.'
fi

printf '\n%s\n' '== Entry points and generated/ignored runtime files =='
report_path "$configured_dir" 'hypr config directory'
for rel in \
  hyprland.lua \
  hyprland.conf \
  UserConfigs/Host.conf \
  UserConfigs/UserKeybinds.conf \
  UserConfigs/UserSettings.conf \
  UserConfigs/WindowRules.conf \
  monitors.conf \
  workspaces.conf \
  UserConfigs/LaptopDisplay.conf \
  wallust/wallust-hyprland.conf \
  wallpaper_effects/.wallpaper_current \
  .initial_startup_done \
  configs \
  scripts \
  UserScripts
do
  report_path "$configured_dir/$rel" "$rel"
done

if [[ -f "$configured_dir/hyprland.lua" ]]; then
  if grep -q 'AUTOGENERATED HYPRLAND CONFIG' "$configured_dir/hyprland.lua"; then
    echo 'Lua entrypoint: autogenerated Hyprland example (not JaKooLit).'
  else
    echo 'Lua entrypoint: non-default file; inspect before replacing.'
  fi
fi
if [[ -f "$configured_dir/hyprland.conf" ]]; then
  if grep -q 'source = \$RepoRoot/common/hyprland.conf' "$configured_dir/hyprland.conf"; then
    echo 'Legacy entrypoint: original managed JaKooLit profile wrapper.'
  fi
fi

printf '\n%s\n' '== Profile / guard =='
if [[ -f "$HOME/.config/environment.d/99-hypr.conf" ]]; then
  grep '^HYPR_PROFILE=' "$HOME/.config/environment.d/99-hypr.conf" || true
else
  echo 'No HYPR_PROFILE environment file.'
fi
if command -v systemctl >/dev/null 2>&1; then
  for unit in hypr-config-guard.path hypr-config-guard.service; do
    printf '%s: ' "$unit"
    systemctl --user is-active "$unit" 2>/dev/null || true
  done
fi

printf '\n%s\n' '== Running compositor =='
if command -v hyprctl >/dev/null 2>&1; then
  hyprctl version | head -n 2 || true
  hyprctl configerrors || true
fi

printf '\n%s\n' '== Backup advice =='
echo 'Before any activation, preserve a self-contained copy of the active profile:'
echo '  mkdir -p "$HOME/hyprland-recovery-2026-11-08"'
echo '  cp -aL -- "$(readlink -f "$HOME/.config/hypr")" "$HOME/hyprland-recovery-2026-11-08/active-copy"'
echo '  readlink "$HOME/.config/hypr" > "$HOME/hyprland-recovery-2026-11-08/link-target.txt"'
echo 'The -L option follows the internal symlinks so this snapshot contains file contents.'
echo 'Preflight complete. Nothing was modified.'
