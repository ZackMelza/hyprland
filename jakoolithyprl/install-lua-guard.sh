#!/usr/bin/env bash
# Install only the Lua entrypoint systemd guard (no profile rebuild, no sudo).
set -euo pipefail
usage() {
  echo "Usage: $0 --check|--install"
  echo "  --check   Show planned guard state without modifications"
  echo "  --install Back up old user units and watch hyprland.lua"
}
[[ $# == 1 ]] || { usage >&2; exit 2; }
case "$1" in --check|--install) ;; *) usage >&2; exit 2;; esac
mode="$1"
script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
source_entry="$script_dir/common/hyprland.lua"
guard_script="$script_dir/common/scripts/GuardHyprConfig.sh"
active="$HOME/.config/hypr"
unit_dir="$HOME/.config/systemd/user"
service="$unit_dir/hypr-config-guard.service"
path_unit="$unit_dir/hypr-config-guard.path"

[[ -f "$source_entry" && -f "$guard_script" ]] ||
  { echo 'Managed Lua entrypoint or guard script missing' >&2; exit 1; }
[[ -L "$active/hyprland.lua" &&
   "$(readlink -f "$active/hyprland.lua")" == "$source_entry" ]] ||
  { echo 'Active Lua config is not the expected managed symlink; refusing' >&2; exit 1; }
[[ -L "$active/lua" &&
   "$(readlink -f "$active/lua")" == "$script_dir/common/lua" ]] ||
  { echo 'Active Lua modules are not the expected managed symlink; refusing' >&2; exit 1; }

echo "Source: $source_entry"
echo "Guard: $guard_script"
echo "User units: $service, $path_unit"
if [[ "$mode" == --check ]]; then
  if [[ -f "$path_unit" ]]; then
    grep -E '^PathChanged=' "$path_unit" || true
  fi
  echo 'Dry check complete. No changes made.'
  exit 0
fi

command -v systemctl >/dev/null 2>&1 ||
  { echo 'systemctl not found; refusing' >&2; exit 1; }
mkdir -p "$unit_dir"
for file in "$service" "$path_unit"; do
  if [[ -e "$file" || -L "$file" ]]; then
    backup="$file.bak.$(date +%Y%m%d%H%M%S)"
    cp -a -- "$file" "$backup"
    echo "Backup: $backup"
  fi
done

cat > "$service" <<'UNIT'
[Unit]
Description=Restore managed Hyprland Lua entrypoint if autogenerated config replaces it

[Service]
Type=oneshot
ExecStart=%h/.config/hypr/scripts/GuardHyprConfig.sh
UNIT

cat > "$path_unit" <<'UNIT'
[Unit]
Description=Watch managed Hyprland Lua entrypoint

[Path]
PathChanged=%h/.config/hypr/hyprland.lua
Unit=hypr-config-guard.service

[Install]
WantedBy=default.target
UNIT

systemctl --user daemon-reload
systemctl --user enable hypr-config-guard.path
systemctl --user restart hypr-config-guard.path
"$guard_script"
echo 'Lua entrypoint guard installed. Other active configuration left unchanged.'
